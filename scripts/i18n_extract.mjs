#!/usr/bin/env node
/**
 * Collect the interface messages (issue #71) and write the English catalog
 * `src/i18n/en.ts`. A message is the string literal passed to `t(`, `tr(` or
 * `msg(`, or the two literals passed to `tp(`, in any `.ts`/`.tsx` file under
 * `src/` (the catalogs themselves excluded). Run after adding or changing an
 * interface text: `node scripts/i18n_extract.mjs`; the German catalog
 * (`src/i18n/de.ts`) then fails the type check until every key is translated.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const LITERAL = String.raw`'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"`
const SINGLE = new RegExp(String.raw`(?<![\w.$])(?:t|tr|msg)\(\s*(${LITERAL})`, 'g')
const PLURAL = new RegExp(String.raw`(?<![\w.$])tp\(\s*(${LITERAL})\s*,\s*(${LITERAL})`, 'g')

const unquote = literal => literal[0] === '"' ? JSON.parse(literal) : JSON.parse(`"${literal.slice(1, -1).replace(/\\'/g, "'").replace(/"/g, '\\"')}"`)

function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) return files(path)
    return /\.tsx?$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name) ? [path] : []
  })
}

/** Every message key used under `src/`, sorted, without duplicates. */
export function extractMessages(root) {
  const src = join(root, 'src')
  const keys = new Set()
  for (const file of files(src)) {
    if (relative(src, file).startsWith('i18n')) continue
    const text = readFileSync(file, 'utf8')
    for (const match of text.matchAll(SINGLE)) keys.add(unquote(match[1]))
    for (const match of text.matchAll(PLURAL)) { keys.add(unquote(match[1])); keys.add(unquote(match[2])) }
  }
  return [...keys].sort((a, b) => a < b ? -1 : a > b ? 1 : 0)
}

export function catalogSource(keys) {
  return `// Generated by scripts/i18n_extract.mjs from the t(), tp(), tr() and msg()
// calls under src/. Do not edit by hand: run \`node scripts/i18n_extract.mjs\`.
// English is the source language, so each key is its own English text.
export const EN_MESSAGES = [
${keys.map(key => `  ${JSON.stringify(key)},`).join('\n')}
] as const

export type MessageKey = typeof EN_MESSAGES[number]
`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
  const keys = extractMessages(root)
  writeFileSync(join(root, 'src/i18n/en.ts'), catalogSource(keys))
  console.log(`src/i18n/en.ts: ${keys.length} messages`)
}
