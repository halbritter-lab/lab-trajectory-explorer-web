import { beforeEach, describe, it, expect } from 'vitest'
import { act, fireEvent, render, screen } from '@testing-library/react'
import { Methodology } from '../../../src/workspace/methods/Methodology'

function topic(id: string) {
  act(() => {
    window.history.replaceState(null, '', `/#methods/${id}`)
    window.dispatchEvent(new HashChangeEvent('hashchange'))
  })
}
function details() {
  fireEvent.click(screen.getByText('Calculation details'))
  // Scientific wording remains available within the individual detail groups.
  for (const summary of document.querySelectorAll('.methodology-detail > summary')) fireEvent.click(summary)
}

describe('Methodology', () => {
  beforeEach(() => window.history.replaceState(null, '', '/'))
  it('explains AKI serum creatinine units, conversion and numeric boundary tolerance', () => {
    topic('aki')
    render(<Methodology />)
    expect(screen.getByText(/AKI detection accepts serum creatinine in mg\/dl or µmol\/l; µmol\/l values are divided by 88\.42 before KDIGO comparisons/i)).toBeInTheDocument()
    expect(screen.getByText(/KDIGO thresholds use an inclusive 1e-12 numeric tolerance/i)).toBeInTheDocument()
    expect(screen.getByText(/≥ 1\.5× that lowest value, or ≥ 0\.3 mg\/dl above it/i)).toBeInTheDocument()
    expect(screen.getByText('An episode gets the highest stage that any of its values reaches.')).toBeInTheDocument()
  })
  it('keeps the workflow and reference available under their own topics', () => {
    render(<Methodology />)
    expect(screen.getByRole('heading', { name: 'Quick Guide' })).toBeInTheDocument()
    expect(screen.getByRole('navigation', { name: 'Help topics' })).toBeInTheDocument()
    expect(screen.getByText(/Load or upload a workbook/i)).toBeInTheDocument()
    expect(screen.getByText(/Use Cohort models for population-level estimates/i)).toBeInTheDocument()
    topic('fits')
    details()
    expect(screen.getByRole('heading', { name: 'Fit Pipeline' })).toBeInTheDocument()
    expect(screen.getByText(/Data filter/)).toBeInTheDocument()
    expect(screen.getByText('Time balancing', { selector: 'strong' })).toBeInTheDocument()
    expect(screen.getByText('Fit model', { selector: 'strong' })).toBeInTheDocument()
    topic('sources')
    expect(screen.getByRole('heading', { name: /medical sources/i })).toBeInTheDocument()
    expect(screen.getByRole('link', { name: /national kidney foundation formula page/i })).toHaveAttribute('href', expect.stringContaining('kidney.org'))
    expect(screen.getByRole('link', { name: /kdigo 2012 clinical practice guideline/i })).toHaveAttribute('href', expect.stringContaining('KDIGO-2012-AKI-Guideline-English.pdf'))
  })
  // Part B of the wording drafts, approved by the owner on 2026-10-08.
  it('covers presets, time balancing, OLS, AKI timing, eGFR conditions, demographics and cohort models', () => {
    render(<Methodology />)
    topic('fits')
    details()
    expect(screen.getByText(/give the quarterly point 45\.5 on 20 February 2021/)).toBeInTheDocument()
    expect(screen.getByText(/56 on 1 January 2021 give −3\.99 per year/)).toBeInTheDocument()
    topic('data')
    details()
    expect(screen.getByText(/gives 29\.96, which is stored as 30\.0/)).toBeInTheDocument()
    topic('fits')
    details()
    expect(screen.getByText(/with three or more points it is unavailable when all fitted values are identical/)).toBeInTheDocument()
    topic('data')
    details()
    expect(screen.getByText(/birth date on the earliest dated lab row that carries one/)).toBeInTheDocument()
    topic('aki')
    details()
    expect(screen.getByText(/onset 2 January 2020 excludes 2 January to 1 February 2020/)).toBeInTheDocument()
    topic('fits')
    details()
    expect(screen.getByText(/Every preset sets the rapid-decline threshold to 5 mL\/min\/1\.73 m² per year/)).toBeInTheDocument()
  })
  // Draft G1, applied 2026-11-22 (OD-34 resolved by the owner).
  it('states how several creatinine values on one day are ordered in AKI detection', () => {
    topic('aki')
    render(<Methodology />)
    details()
    expect(screen.getByText(/^Lab dates are calendar days\. The 48-hour window covers earlier measurements one or two calendar days earlier/)).toBeInTheDocument()
    expect(screen.getByText(/Several creatinine values on one day are ordered by their time of day when the file gives one for each of them/)).toBeInTheDocument()
    expect(screen.getByText(/so a rise within that day is not detected on that day\. The Data page states how many patient-days this concerns\./)).toBeInTheDocument()
    expect(screen.queryByText(/calendar days without a time of day/)).not.toBeInTheDocument()
  })
  // Parts C, D and E1 of the wording drafts, approved by the owner on 2026-11-16.
  it('states the rules changed since the clinical review as the code applies them', () => {
    render(<Methodology />)
    topic('data')
    expect(screen.getByText('CKD-EPI 2009 (race-free)', { selector: 'strong' })).toBeInTheDocument()
    expect(screen.getByText(/above 25 mg\/dl \(2210\.5 µmol\/l\)/)).toBeInTheDocument()
    expect(screen.getByText(/A\s+value of exactly 25 mg\/dl or exactly 200 gives no warning/)).toBeInTheDocument()
    expect(screen.getByText(/lists such series under “Not used for this eGFR”/)).toBeInTheDocument()
    topic('aki')
    expect(screen.getByText(/A single letter “U” in the name also counts as urine/)).toBeInTheDocument()
    expect(screen.getByText(/A computed eGFR column\s+uses the creatinine series it was computed from/)).toBeInTheDocument()
    topic('endpoints')
    details()
    expect(screen.getByText('G5 < 3 dates', { selector: 'strong' })).toBeInTheDocument()
    expect(screen.getByText('G5 not projected after KRT', { selector: 'strong' })).toBeInTheDocument()
    expect(screen.queryByText('G5 n < 3', { selector: 'strong' })).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Individual endpoint projection algorithm' })).toBeInTheDocument()
    expect(screen.getByText(/Require measurements on at least three different dates \(five with Theil–Sen\)/)).toBeInTheDocument()
    expect(screen.getByText(/A missing\s+projected age does not mean a stable course/)).toBeInTheDocument()
    expect(screen.getByText(/The 57% threshold only approximates a doubling of serum creatinine/)).toBeInTheDocument()
    expect(document.body.textContent).not.toMatch(/Display-fit AKI exclusions|aggregation|Theil-Sen|1\.73m²/)
    topic('fits')
    details()
    expect(screen.getByRole('region', { name: 'Settings that change which measurements are fitted' })).toBeInTheDocument()
    expect(screen.getByText(/fitted measurements on fewer than three different dates/)).toBeInTheDocument()
    expect(document.body.textContent).not.toMatch(/Display-fit AKI exclusions|aggregat|Theil-Sen|1\.73m²/)
    topic('sources')
    expect(screen.getByRole('heading', { name: 'Rules of this tool that are not published standards' })).toBeInTheDocument()
    expect(screen.getByText(/they have not been validated against\s+outcomes/)).toBeInTheDocument()
    expect(screen.getByRole('link', { name: /Levey AS et al\., Annals of Internal Medicine 2009;150\(9\):604–612/ })).toHaveAttribute('href', 'https://doi.org/10.7326/0003-4819-150-9-200905050-00006')
  })
  it('keeps one description of the age anchor and points the eGFR age input to it', () => {
    topic('data')
    render(<Methodology />)
    details()
    expect(screen.getAllByText(/the anchor is the midpoint of their intersection/)).toHaveLength(1)
    expect(screen.getByText(/derives every row's age from one birth-date anchor per patient/)).toBeInTheDocument()
    expect(screen.getByText(/A stated age that contradicts the others is corrected rather than used/)).toBeInTheDocument()
    expect(screen.queryByText(/taken from a manual entry, an explicit birth date, or the stated ages/)).not.toBeInTheDocument()
  })
})
