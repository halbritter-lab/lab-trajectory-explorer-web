import { expect, test } from '@playwright/test'
import * as XLSX from 'xlsx'

test('real workbook previews complete-case factor selection before applying', async ({ page }) => {
  const wb = XLSX.utils.book_new()
  const ids = Array.from({length:9}, (_,index) => index + 1)
  const labs = ids.flatMap((patientId) => [0,1,2].map((year) => ({patientId,labDate:`${2022+year}-01-01`,testName:'eGFR',unit:'ml/min/1.73m2',value:80-patientId-year,ageAtLab:40+patientId*2+year,sex:patientId%2 ? 'm':'w'})))
  const attributes = ids.map((patientId) => ({patientId,genotype:patientId === 9 ? '' : patientId%3 ? 'A':'B'}))
  XLSX.utils.book_append_sheet(wb,XLSX.utils.json_to_sheet(labs),'labs')
  XLSX.utils.book_append_sheet(wb,XLSX.utils.json_to_sheet(attributes),'attributes')
  await page.goto('/')
  await page.locator('main input[type=file]').setInputFiles({name:'model-factors.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:XLSX.write(wb,{type:'buffer',bookType:'xlsx'})})
  await expect(page.getByRole('status')).toContainText('Loaded 27 rows')
  await page.getByRole('button',{name:'Cohort',exact:true}).click()
  await page.getByRole('combobox',{name:'Series 1 parameter'}).fill('eGFR')
  await page.getByRole('option',{name:/^eGFR \(ml\/min\/1.73m2\)$/}).click()
  await page.getByRole('button',{name:'Open eGFR cohort model'}).click()
  const dialog = page.getByRole('dialog',{name:'eGFR cohort model'})
  await expect(dialog.getByLabel('genotype effect')).toHaveValue('excluded')
  await dialog.getByRole('button',{name:'Use genotype example'}).click()
  await expect(dialog.getByRole('button',{name:'Apply settings'})).toBeDisabled()
  await expect(dialog.getByLabel('Baseline age interpretation')).toBeDisabled()
  await dialog.getByLabel('genotype reference').selectOption('A')
  await dialog.getByLabel('Sex reference').selectOption('m')
  await expect(dialog.getByLabel('Model population preview')).toContainText('8 patients / 9; 24 measurements / 27')
  await expect(dialog.getByLabel('Model population preview')).toContainText('9: Missing genotype')
  await dialog.getByText('Formula preview',{exact:true}).click()
  await expect(dialog.getByLabel('Readable formula')).toContainText('Time (years):"genotype"')
  await dialog.getByRole('button',{name:'Apply settings'}).click()
  await expect(dialog.getByTestId('cohort-model-row').getByRole('cell').nth(2)).toHaveText('8')
  await expect(dialog.getByRole('columnheader',{name:'Reference slope',exact:true})).toBeVisible()
  await expect(dialog.getByRole('button',{name:'Export models (xlsx)'})).toBeDisabled()
})
